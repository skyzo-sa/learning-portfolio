print('#' * 10 + 'COMPARISON OPERATORS' + '#' * 10)

"""
Comparison Operators:
"""

# (==) Equality
print(7 == 8) # => False
print('abc' == 'abc') # => True


# (!=) Inequality, Not Equals too
print( 7 != 7) # => False
print('a' != 'A') # => True


# (>) Greater than
a, b = 7, 9
print(a > b) # => False


# (>=) Greater than or equal to
print(b >= 9) # returns => True


# (<) Lesser than
print(a < 9) # returns => True


# (<=) Lesser than or equal to
print(a * 2 <= 100) # returns => True